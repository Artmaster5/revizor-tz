AND_OR = re.compile(r"\bи/или\b|\band/or\b|\bили/и\b", _I)
WEAK_MODAL = re.compile(
    r"\b(?:может|могут|желательно|возможно|опционально|по желанию|следует|рекомендуется|допускается|"
    r"may|might|could|should|optionally|preferably|ideally)\b",
    _I,
)
MANDATORY = re.compile(r"\b(?:долж[её]?н\w*|обязан\w*|необходимо|требуется|shall|must|required)\b", _I)
EXAMPLE = re.compile(r"\b(?:например|к примеру|в том числе|такие как|e\.g\.|for example|such as|for instance)\b", _I)

_CANDIDATE_KINDS = ("paragraph", "list_item")


def _make_rule(rx: re.Pattern, title: str, problem: str, recommendation: str, question: str, options: list[str],
               extra=None):
    def rule_fn(ctx: Ctx, rule):
        out = []
        for b in ctx.req_blocks:
            if b.kind not in _CANDIDATE_KINDS:
                continue
            t = visible(b.text)
            m = rx.search(t)
            if not m or (extra is not None and not extra(t, m)):
                continue
            w = m.group(0).strip()
            out.append(finding(
                rule, [ctx.q_sentence(b, m.start())],
                title=title.format(w=short(w, 30)),
                problem=problem.format(w=short(w, 30)),
                recommendation=recommendation.format(w=short(w, 30)),
                question=ask(question.format(w=short(w, 30)), options),
            ))
        return out
    return rule_fn


