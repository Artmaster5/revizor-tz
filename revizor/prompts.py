# --- token estimate ------------------------------------------------------------------------------

_CYR = re.compile(r"[Ѐ-ӿ]")


def approx_tokens(text: str) -> int:
    """Rough token count: Cyrillic letters ÷ 2.6 + every other character ÷ 3.6.

    Calibrated by eye on BPE tokenizers of large models (Russian text costs more tokens per letter than
    English). Expect ±25 %; the real number comes from the provider's usage report."""
    if not text:
        return 0
    cyr = len(_CYR.findall(text))
    return int(round(cyr / 2.6 + (len(text) - cyr) / 3.6))
