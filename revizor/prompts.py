SLICE_HEAD = """ЗАДАЧА: нарезка документа на требования.
Ниже блоки документа по порядку: id, тип, раздел, текст. Отнеси каждый блок либо к требованиям, либо к пропущенным.

Требование — утверждение о том, что система, интерфейс, данные, интеграция или процесс должны делать или какими быть. Сюда же относятся цели, ограничения, шаги логики, правила, параметры и статусы интерфейсов, критерии приёмки.
Единица нарезки — один пункт списка, один абзац, одна строка таблицы или один шаг. Не дроби пункт на предложения: если в нём несколько независимых утверждений, оставь его целым (это отдельный дефект — неатомарность).
Объединяй соседние блоки в одно требование, только если по отдельности они не имеют смысла (например, описание статуса и пример ответа к нему).
Пропущенные — заголовки, оглавление, служебные сведения о документе (название, автор, ссылки), пояснения, пустые шаблоны и незаполненные чек-листы. Заглушки и пустые разделы тоже идут в пропущенные с категорией placeholder: они будут проверены на уровне набора.
Каждый блок должен попасть ровно в один элемент ответа.

ФОРМА ОТВЕТА:
{"requirements":[{"block_ids":["B012"],"doc_id":"номер из документа или пустая строка","kind":"goal|functional|nonfunctional|data|integration|api|ui|process|acceptance|constraint|other","summary":"суть требования своими словами, до 120 знаков"}],
 "skipped":[{"block_ids":["B001"],"category":"heading|meta|explanation|template|placeholder|other","reason":"почему это не требование, до 100 знаков"}]}
"""


def block_lines(doc: SourceDoc, only: set[str] | None = None) -> str:
    out = []
    for b in doc.blocks:
        if only is not None and b.bid not in only:
            continue
        out.append(json.dumps({"id": b.bid, "kind": b.kind, "section": b.section, "text": b.text}, ensure_ascii=False))
    return "\n".join(out)


def slice_user(doc: SourceDoc, inj: str = "") -> str:
    return SLICE_HEAD + inj + "\n\nБЛОКИ:\n" + block_lines(doc)


def slice_rest_user(doc: SourceDoc, missing: list[str], inj: str = "") -> str:
    head = SLICE_HEAD.replace(
        "Ниже блоки документа по порядку",
        "В прошлом ответе эти блоки не попали ни в требования, ни в пропущенные. Ниже только они, по порядку")
    return head + inj + "\n\nБЛОКИ:\n" + block_lines(doc, set(missing))


